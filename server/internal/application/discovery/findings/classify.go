func (l lang) cLike() bool {
	switch l {
	case langGo, langJS, langJava, langKotlin, langSwift, langDart, langPHP, langCSharp, langRust:
		return true
	}
	return false
}

func (l lang) hashComments() bool { return l == langPython || l == langRuby }

type fileKind int

const (
	kindOther fileKind = iota
	kindSource
	kindConfig
	kindEnv
)

type fileInfo struct {
	path string
	base string
	kind fileKind
	lang lang
	// test files only count toward "has tests"; no rule reads them, since
	// fixtures and fake credentials are what tests are for.
	test bool
	// aux files (scripts, tools, examples, docs) are code nobody deploys, so
	// rules about what reaches production skip them.
	aux bool
}

var configExts = map[string]bool{
	".yaml": true, ".yml": true, ".json": true, ".properties": true, ".xml": true, ".plist": true,
	".toml": true, ".ini": true, ".conf": true, ".cfg": true, ".gradle": true, ".tf": true,
	".tfvars": true, ".pro": true, ".hcl": true,
}

var skippedBases = map[string]bool{
	"package-lock.json": true, "yarn.lock": true, "pnpm-lock.yaml": true, "go.sum": true,
	"Cargo.lock": true, "composer.lock": true, "Gemfile.lock": true, "poetry.lock": true,
	"Podfile.lock": true, "Package.resolved": true, "pubspec.lock": true, "bun.lockb": true,
	"tsconfig.tsbuildinfo": true, "uv.lock": true, "Pipfile.lock": true,
}

var testSegments = map[string]bool{
	"test": true, "tests": true, "__tests__": true, "spec": true, "specs": true, "e2e": true,
	"cypress": true, "playwright": true, "testdata": true, "fixtures": true, "__fixtures__": true,
	"__mocks__": true, "mocks": true, "mock": true, "androidtest": true, "testing": true,
	"test-utils": true, "testutils": true, "integration-tests": true, "uitests": true,
}

var auxSegments = map[string]bool{
	"scripts": true, "script": true, "tools": true, "hack": true, "examples": true, "example": true,
	"samples": true, "sample": true, "docs": true, "doc": true, "bench": true, "benchmarks": true,
	"migrations": true, "seeds": true, "seed": true, "notebooks": true, "demo": true, "demos": true,
	"playground": true, ".storybook": true, "storybook": true, "stories": true, "cmd": true,
}

var testBase = regexp.MustCompile(`(?i)(_test\.go$|\.(test|spec|stories|story|e2e)\.[a-z]+$|^test_.*\.py$|_test\.py$|^conftest\.py$|(Test|Tests|Spec)\.(java|kt|swift|cs)$|_spec\.rb$|_test\.dart$|_test\.rb$)`)

var generatedBase = regexp.MustCompile(`(?i)(\.pb(\.gw)?\.go$|_gen\.go$|\.gen\.[a-z]+$|generated|\.g\.dart$|\.freezed\.dart$|\.designer\.cs$|\.min\.[a-z]+$|\.bundle\.js$|\.d\.ts$|^R\.java$|^BuildConfig\.java$|\.chunk\.js$)`)

func classify(p string) fileInfo {
	base := path.Base(p)
	info := fileInfo{path: p, base: base}
	if skippedBases[base] || generatedBase.MatchString(base) {
		return info
	}
	lower := strings.ToLower(p)
	for _, seg := range strings.Split(path.Dir(lower), "/") {
		if testSegments[seg] || strings.HasSuffix(seg, "tests") {
			info.test = true
		}
		if auxSegments[seg] {
			info.aux = true
		}
	}
	if strings.Contains(lower, "/src/test/") || strings.HasPrefix(lower, "src/test/") {
		info.test = true
	}
	if testBase.MatchString(base) {
		info.test = true
	}

	if base == ".env" || strings.HasPrefix(base, ".env.") {
		info.kind = kindEnv
		return info
	}
	ext := strings.ToLower(path.Ext(base))
	if l, ok := extLang[ext]; ok {
		info.kind = kindSource
		info.lang = l
		return info
	}
	if configExts[ext] || isDockerfile(base) || strings.HasSuffix(base, ".gradle.kts") {
		info.kind = kindConfig
	}
	return info
}

func isDockerfile(base string) bool {
	lower := strings.ToLower(base)
	return lower == "dockerfile" || strings.HasPrefix(lower, "dockerfile.") || strings.HasSuffix(lower, ".dockerfile")
}

var generatedHeader = regexp.MustCompile(`(?i)(code generated|@generated|do not edit|auto-generated|autogenerated|generated by)`)

func generatedContent(content string) bool {
	head := content
	if len(head) > 600 {
		head = head[:600]
	}
	return generatedHeader.MatchString(head)
}

var (
	prodPathRe = regexp.MustCompile(`(^|[/._-])(prod|production|live|release)([/._-]|$)`)
	devPathRe  = regexp.MustCompile(`(^|[/._-])(dev|develop|development|local|test|testing|example|examples|sample|template|ci|e2e|mock|fixture|fixtures|demo|stage|staging|debug|override)([/._-]|$)`)
)

// prodOnly is a file whose name or directory says it configures production
// and nothing else, so a debug setting in it ships.
func prodOnly(p string) bool {
	lower := strings.ToLower(p)
	return prodPathRe.MatchString(lower) && !devPathRe.MatchString(lower)
}

func devOnly(p string) bool { return devPathRe.MatchString(strings.ToLower(p)) }
